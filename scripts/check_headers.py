from __future__ import annotations

from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]

EXCLUDED_DIRS = {
    ".git",
    "node_modules",
    "vendor",
    "dist",
    "build",
    "bin",
    "obj",
    ".next",
    "coverage",
    ".vs",
    ".vscode",
}

EXCLUDED_SUFFIXES = (
    ".lock",
    ".db",
    ".sqlite",
    ".png",
    ".jpg",
    ".jpeg",
    ".gif",
    ".svg",
    ".ico",
    ".pdf",
    ".woff",
    ".woff2",
    ".ttf",
    ".md",
    ".json",
    ".yml",
    ".yaml",
    ".toml",
)

VALID_EXTENSIONS = {".cs", ".ts", ".tsx", ".js", ".jsx", ".py"}


def should_skip(path: Path) -> bool:
    if any(part in EXCLUDED_DIRS for part in path.parts):
        return True
    if path.name.startswith(".") and path.name not in {".csproj", ".props", ".targets"}:
        return True
    if path.suffix.lower() in EXCLUDED_SUFFIXES:
        return True
    if path.suffix.lower() not in VALID_EXTENSIONS:
        return True
    return False


def has_header(content: str) -> bool:
    return all(
        re.search(pattern, content, re.IGNORECASE)
        for pattern in (
            r"Autor\s*:\s*.+",
            r"Fecha\s*:\s*\d{4}-\d{2}-\d{2}",
            r"Versión\s*:\s*.+",
            r"Descripción\s*:\s*.+",
        )
    )


def iter_paths(targets: list[str] | None) -> list[Path]:
    if targets:
        candidates: list[Path] = []
        for raw in targets:
            if not raw or raw == "-":
                continue
            path = (ROOT / raw).resolve()
            if path.is_file() and not should_skip(path):
                candidates.append(path)
        return sorted(candidates)

    return sorted(
        path
        for path in ROOT.rglob("*")
        if path.is_file() and not should_skip(path)
    )


def main(argv: list[str] | None = None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    missing: list[str] = []

    for path in iter_paths(argv):
        try:
            content = path.read_text(encoding="utf-8", errors="ignore")
        except OSError:
            continue

        if not content.strip():
            continue

        if "Generated by" in content or "DO NOT EDIT" in content:
            continue

        if not has_header(content[:2000]):
            missing.append(str(path.relative_to(ROOT)))

    if missing:
        print("Falta cabecera en archivos propios del repositorio:")
        for item in missing:
            print(f" - {item}")
        print("\nAñade una cabecera con Autor, Fecha, Versión y Descripción.")
        return 1

    print("Cabeceras OK: los archivos revisados tienen metadatos.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
